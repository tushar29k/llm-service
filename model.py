"""Everything in this service talks to models through LocalLLM — one
interface, two backends.

MockBackend: fake, instant, zero downloads. Answers are templated so it's
dumb as rocks, but that's fine — it's just here so you can build the API,
prompts, retries and benchmarks against something.

HFBackend: a real Hugging Face model. Needs torch + transformers +
accelerate, and honestly a GPU for anything above ~3B.

Swap between them with one line in config.yaml:  backend: mock -> hf
"""
import json
import time
import re

import yaml


# ---------------------------------------------------------------- backends
class MockBackend:
    """Not a real model — templated answers, runs instantly. Good enough
    to build everything else against."""

    def generate(self, prompt, max_new_tokens=256, temperature=0.7):
        if "JSON" in prompt:
            return '{"order_id": "ORD-1", "items": 2}'
        return ("This is a mock completion. In production this text would be "
                "generated by the loaded model.")

    def stream(self, prompt, max_new_tokens=256):
        for word in self.generate(prompt, max_new_tokens).split():
            time.sleep(0.005)
            yield word + " "


class HFBackend:
    """The real thing. pip install torch transformers accelerate first,
    and ideally have a GPU handy."""

    def __init__(self, model_id, dtype="float16"):
        import torch
        from transformers import AutoTokenizer, AutoModelForCausalLM
        self.torch = torch
        self.tok = AutoTokenizer.from_pretrained(model_id)
        self.model = AutoModelForCausalLM.from_pretrained(
            model_id, torch_dtype=getattr(torch, dtype), device_map="auto")

    def _inputs(self, prompt):
        return self.tok(prompt, return_tensors="pt").to(self.model.device)

    def generate(self, prompt, max_new_tokens=256, temperature=0.7):
        inputs = self._inputs(prompt)
        out = self.model.generate(**inputs, max_new_tokens=max_new_tokens,
                                  temperature=temperature, do_sample=True)
        return self.tok.decode(out[0][inputs.input_ids.shape[1]:],
                               skip_special_tokens=True)

    def stream(self, prompt, max_new_tokens=256):
        from transformers import TextIteratorStreamer
        from threading import Thread
        inputs = self._inputs(prompt)
        streamer = TextIteratorStreamer(self.tok, skip_special_tokens=True)
        Thread(target=self.model.generate,
               kwargs={**inputs, "max_new_tokens": max_new_tokens,
                       "streamer": streamer}, daemon=True).start()
        yield from streamer


# ---------------------------------------------------------------- LLM
class LocalLLM:
    def __init__(self, config_path="config.yaml"):
        self.cfg = yaml.safe_load(open(config_path))
        if self.cfg.get("backend", "mock") == "hf":
            self.backend = HFBackend(self.cfg["model_id"],
                                     self.cfg.get("dtype", "float16"))
        else:
            self.backend = MockBackend()
        # prompts live as versioned files, not inline strings — much easier
        # to diff v1 vs v2 later when something regresses
        self.prompt_dir = self.cfg.get("prompt_dir", "prompts/v1")

    def load_prompt(self, name, **kwargs):
        text = open(f"{self.prompt_dir}/{name}.txt").read()
        return text.format(**kwargs)

    def build_prompt(self, messages):
        # cheap stand-in for a chat template; the HF path uses the
        # tokenizer's real chat template instead
        if isinstance(self.backend, HFBackend):
            return self.backend.tok.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=True)
        return "\n".join(f"{m['role']}: {m['content']}" for m in messages
                         ) + "\nassistant:"

    def chat(self, messages, max_new_tokens=256, temperature=0.7):
        return self.backend.generate(self.build_prompt(messages),
                                     max_new_tokens, temperature)

    def chat_stream(self, messages, max_new_tokens=256):
        yield from self.backend.stream(self.build_prompt(messages),
                                       max_new_tokens)

    # -- structured output: ask -> check what came back -> show the model
    #    its mistake and try again ----------------------------------------
    @staticmethod
    def _extract_json(text, required):
        # cheap trick: grab the outermost { ... } instead of trusting the
        # model to output *only* JSON (it rarely does on the first try)
        start, end = text.find("{"), text.rfind("}")
        if start == -1:
            return None, "no JSON object found"
        try:
            obj = json.loads(text[start:end + 1])
        except json.JSONDecodeError as e:
            return None, f"invalid JSON: {e}"
        missing = [f for f in required if f not in obj]
        if missing:
            return None, f"missing fields: {missing}"
        return obj, None

    def extract_json(self, prompt, required, retries=2):
        prompt = prompt + "\nRespond with ONLY a JSON object."
        for _ in range(retries + 1):
            raw = self.backend.generate(prompt)
            obj, err = self._extract_json(raw, required)
            if obj:
                return obj
            prompt += f"\nYour last output had an error: {err}. Fix it."
        raise ValueError("model failed to produce valid JSON after retries")
